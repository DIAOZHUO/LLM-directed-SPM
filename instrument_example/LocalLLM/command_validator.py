"""
Deterministic validation of the command sequences generated by the command SLM.

The checks do not rely on the language model:
  - format: every line inside <cmd>...</cmd> must match a command of the API reference (spm_command.csv);
    otherwise the whole sequence is rejected (no partial execution)
  - numerical bounds of each parameter (instrument specification)
  - state-dependent constraints, evaluated by simulating the sequence from the current instrument state
    (probe position, scan size, scanning or not)

This module does not depend on the instrument framework, so it can be tested offline.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, replace
from typing import Optional, List, Tuple

from .cmd_eval_util import parse_line

# accessible range of the probe (tube scanner), in nm; the scan area is centered at the probe position
STAGE_LIMIT_NM = 350.0

# AI modules that move the probe; the position is unknown until the module has finished
POSITION_CHANGING_COMMANDS = {"DriftCompensation", "TipFix", "SwitchScanarea"}


class CommandRejected(Exception):
    pass


@dataclass(frozen=True)
class SPMState:
    x_nm: Optional[float]       # probe position, None if unknown
    y_nm: Optional[float]
    size_x_nm: float            # scan size
    size_y_nm: float
    scanning: bool


@dataclass(frozen=True)
class Command:
    method: str
    arg: object                 # float / bool / None (commands without argument)


def extract_commands(response: str, schema: dict) -> Tuple[bool, str, List[Command]]:
    """
    response of the command SLM -> (is_valid, reason, commands)
    A response starting with 'None' is a rejection by the SLM itself.
    """
    for line in response.split("\n"):
        if line.strip().startswith("None"):
            return False, response[response.index("None") + 4:].strip(". :\n"), []

    blocks = re.findall(r"<cmd>(.*?)</cmd>", response, re.DOTALL)
    if not blocks:
        return False, "no <cmd> block in the response.", []

    commands = []
    for block in blocks:
        for line in block.split("\n"):
            if line.strip() == "":
                continue
            cmd_dict = parse_line(line, schema)
            if cmd_dict is None:
                return False, f"'{line.strip()}' does not match the command specification.", []
            arg = cmd_dict["args"][0] if cmd_dict["args"] else None
            commands.append(Command(cmd_dict["method"], arg))

    if not commands:
        return False, "the <cmd> block is empty.", []
    return True, "", commands


def _check_position(axis: str, value: float):
    if abs(value) > STAGE_LIMIT_NM:
        raise CommandRejected(f"{axis} = {value:g} nm exceeds the accessible range of "
                              f"-{STAGE_LIMIT_NM:g} to {STAGE_LIMIT_NM:g} nm.")


def _check_scan_area(state: SPMState, strict: bool):
    for axis, pos, size in (("X", state.x_nm, state.size_x_nm), ("Y", state.y_nm, state.size_y_nm)):
        if pos is None:
            if strict:
                raise CommandRejected(f"the probe position ({axis}) is unknown.")
            continue
        if abs(pos) + size / 2 > STAGE_LIMIT_NM:
            raise CommandRejected(f"a {size:g} nm scan at {axis} = {pos:g} nm would extend beyond the accessible "
                                  f"range of -{STAGE_LIMIT_NM:g} to {STAGE_LIMIT_NM:g} nm.")


def _move(state: SPMState, axis: str, value: float, relative: bool, strict: bool) -> SPMState:
    key = "x_nm" if axis == "X" else "y_nm"
    current = getattr(state, key)
    if relative:
        if current is None:
            if strict:
                raise CommandRejected(f"the probe position ({axis}) is unknown.")
            return state  # checked again at execution time, when the position is known
        value = current + value
    _check_position(axis, value)
    return replace(state, **{key: value})


def apply_command(state: SPMState, cmd: Command, strict: bool = False) -> SPMState:
    """
    Check one command against the parameter bounds and the instrument state,
    and return the state after the command. Raises CommandRejected.
    strict: reject commands whose validity depends on an unknown probe position
            (False at parse time, True at execution time)
    """
    m, arg = cmd.method, cmd.arg

    if m in ("StageOffset_X_Tube", "StageOffset_X_Tube_ADD"):
        state = _move(state, "X", arg, relative=m.endswith("_ADD"), strict=strict)
    elif m in ("StageOffset_Y_Tube", "StageOffset_Y_Tube_ADD"):
        state = _move(state, "Y", arg, relative=m.endswith("_ADD"), strict=strict)
    # Sample_Bias is not checked here: whether a bias value (e.g. 0 V) is admissible depends on
    # the measurement context, which is evaluated by the command SLM
    elif m in ("Aux1MaxVoltage", "Aux2MaxVoltage"):
        if arg <= 0:
            raise CommandRejected("scan size must be greater than 0.")
        if arg > 2 * STAGE_LIMIT_NM:
            raise CommandRejected(f"scan size {arg:g} nm exceeds the accessible range regardless of the position.")
        state = replace(state, **{"size_x_nm" if m == "Aux1MaxVoltage" else "size_y_nm": arg})
    elif m == "Scan_Speed":
        if arg <= 0:
            raise CommandRejected("scan speed must be greater than 0.")
    elif m == "ScanEnabled":
        if arg is True:
            if state.scanning:
                raise CommandRejected("scan has already started.")
            _check_scan_area(state, strict)
            # the next command is executed after the scan has finished (callback)
            return replace(state, scanning=False)
        if not state.scanning:
            raise CommandRejected("scan has not started.")
        return replace(state, scanning=False)
    elif m in POSITION_CHANGING_COMMANDS:
        return replace(state, x_nm=None, y_nm=None)

    # moving the probe or changing the scan size during an ongoing scan
    if state.scanning:
        _check_scan_area(state, strict)
    return state


def validate_sequence(state: SPMState, commands: List[Command], strict: bool = False) -> Tuple[bool, str]:
    """simulate the whole sequence; one invalid command rejects the whole sequence"""
    for i, cmd in enumerate(commands):
        try:
            state = apply_command(state, cmd, strict)
        except CommandRejected as e:
            arg = "" if cmd.arg is None else cmd.arg
            return False, f"command {i + 1} {cmd.method}({arg}): {e}"
    return True, ""
